-- Repair databases where V1 was baselined or the requests table was missing.
CREATE TABLE IF NOT EXISTS requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(255) NOT NULL,
    description TEXT,
    priority VARCHAR(255) NOT NULL,
    status VARCHAR(255) NOT NULL DEFAULT 'OPEN',
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    user_id BIGINT NOT NULL,
    assigned_to BIGINT,
    CONSTRAINT fk_requests_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_requests_assigned_to FOREIGN KEY (assigned_to) REFERENCES users (id)
);

CREATE INDEX IF NOT EXISTS idx_requests_user_id ON requests (user_id);
CREATE INDEX IF NOT EXISTS idx_requests_assigned_to ON requests (assigned_to);
CREATE INDEX IF NOT EXISTS idx_requests_status ON requests (status);
